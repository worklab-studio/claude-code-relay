/**
 * Programmatic, idempotent schema migration for PGlite (`pnpm dev`, tests) and for
 * a first boot against Neon when `db:push` was not run (§2.3, §10.1).
 *
 * Kept as plain `CREATE ... IF NOT EXISTS` statements mirroring src/db/schema.ts so
 * the Vercel bundle needs no migration folder on disk and boot is deterministic.
 * drizzle-kit (`pnpm db:push`) remains the tool for evolving a live Neon database;
 * bump SCHEMA_VERSION and append ALTER statements here when the schema changes.
 * schema.test.ts inserts into every table through Drizzle, which catches drift
 * between this file and schema.ts.
 */
import { sql } from 'drizzle-orm';
import type { Db } from './client.js';

export const SCHEMA_VERSION = 1;

